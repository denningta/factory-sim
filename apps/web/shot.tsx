import { createRoot } from 'react-dom/client';
import { createEditorStore } from './src/layout/editorStore';
import { ProductsPanel } from './src/products/ProductsPanel';
const store = createEditorStore();
const s = store.getState();
const mk = (x: number, name: string) => {
  const e = s.placeEquipment('base-workstation', { x, y: 2 })!;
  s.updateEquipment(e.id, { name });
  return e.id;
};
const [saw, cnc, wash, pack] = [mk(2, 'Saw'), mk(5, 'CNC'), mk(8, 'Wash'), mk(11, 'Pack')];
const p1 = s.addProduct();
const p2 = s.addProduct();
for (const st of [saw, cnc, wash, pack]) s.addRoutingStep(p1.id, st);
for (const st of [saw, cnc, pack]) s.addRoutingStep(p2.id, st);
s.setCycleTimeDuration(p1.id, saw, { kind: 'fixed', value: 45 });
s.setCycleTimeDuration(p1.id, cnc, { kind: 'normal', mean: 60, stdDev: 8 });
s.setCycleTimeDuration(p1.id, wash, { kind: 'triangular', min: 20, mode: 30, max: 60 });
s.setCycleTimeDuration(p1.id, pack, { kind: 'exponential', mean: 15 });
s.setCycleTimeDuration(p2.id, saw, { kind: 'lognormal', mean: 50, stdDev: 15 });
s.setCycleTimeDuration(p2.id, cnc, { kind: 'normal', mean: 5, stdDev: 8 });
s.setCycleTimeDuration(p2.id, pack, { kind: 'fixed', value: 20 });
createRoot(document.getElementById('root')!).render(<ProductsPanel useStore={store} />);
